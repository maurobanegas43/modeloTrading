"""Puertos que necesita la aplicación; los adaptadores concretos viven fuera."""

from __future__ import annotations

from pathlib import Path
from typing import AsyncIterator, Protocol

import pandas as pd


class BundleStore(Protocol):
    def load(self) -> dict: ...
    def save(self, bundle: dict) -> None: ...
    def modified_at(self) -> float: ...


class ReportStore(Protocol):
    def save(self, report: dict) -> None: ...


class MarketDataPort(Protocol):
    def download_history(self, symbol: str, days: int, existing_path: Path | None = None) -> pd.DataFrame: ...
    def read_history(self, path: Path) -> pd.DataFrame: ...
    def read_recent_local(self, path: Path, bars: int) -> pd.DataFrame: ...
    def recent_closed_candles(self, symbol: str, limit: int = 1000) -> pd.DataFrame: ...


class PaperStatePort(Protocol):
    def load_state(self) -> dict | None: ...
    def save_state(self, state: dict) -> None: ...
    def append_event(self, event: dict) -> None: ...
    def append_prediction(self, prediction: dict) -> None: ...
    def clear_replay(self) -> None: ...
    def write_predictions(self, predictions: list[dict]) -> None: ...
    def load_checkpoint(self) -> dict | None: ...
    def save_checkpoint(self, checkpoint: dict) -> None: ...
    def save_status(self, status: dict) -> None: ...
    def save_summary(self, summary: dict) -> None: ...


class MarketStreamPort(Protocol):
    def events(self, symbol: str) -> AsyncIterator[dict]: ...


class FuturesMarketStreamPort(Protocol):
    def events(self, symbol: str) -> AsyncIterator[dict]: ...
